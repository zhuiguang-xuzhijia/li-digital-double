# ────────────────────────── 提炼 ──────────────────────────

def _口头禅(样们):
    """2–4 字片段，跨 ≥3 条消息、总次数 ≥4。"""
    import collections
    计 = collections.Counter()
    分布 = collections.defaultdict(set)
    for s in 样们:
        原 = str(s.get("话") or "")
        文 = re.sub(r"[^\u4e00-\u9fa5]", "", 原)
        if not 文:
            continue
        # ★ 按句子去重：同一句重复十遍，不算十条不同消息
        见过 = set()
        for n in (2, 3, 4):
            for k in range(0, max(0, len(文) - n + 1)):
                段 = 文[k:k + n]
                if 段 in 停用 or 段 in 见过:
                    continue
                见过.add(段)
                计[段] += 1
                分布[段].add(原)
    好 = [(段, c) for 段, c in 计.items() if c >= 4 and len(分布[段]) >= 3]
    好.sort(key=lambda x: (-len(x[0]), -x[1]))
    出, 用过的 = [], []
    for 段, c in 好:
        if any(段 in u or u in 段 for u in 用过的):
            continue
        出.append(段)
        用过的.append(段)
        if len(出) >= 3:
            break
    return 出


def _提炼一段(样们, 最少=12):
    r"""给一组样本，产出血指纹句子。太少就返回空。"""
    if len(样们) < 最少:
        return []
    话们 = [s["话"] for s in 样们]
    全 = "".join(话们)
    条数 = len(话们)
    出 = []

    禅 = _口头禅(样们)
    if 禅:
        出.append("口头禅：「%s」" % "」「".join(禅))

    习惯 = []
    长们 = sorted(len(t) for t in 话们)
    平均 = sum(len(t) for t in 话们) / float(条数)
    p10 = 长们[int(条数 * 0.1)]
    p90 = 长们[min(条数 - 1, int(条数 * 0.9))]
    if 平均 <= 8:
        习惯.append("句子短，常一句话就完（多数 %d 字上下）" % round(平均))
    elif 平均 >= 26:
        习惯.append("话多，喜欢一长串说完（多数 %d 字上下）" % round(平均))
    else:
        习惯.append("句子长度多数在 %d–%d 字" % (p10, p90))

    语气 = [w for w in 语气词表 if 全.count(w) >= max(3, 条数 * 0.25)]
    if 语气:
        习惯.append("爱带" + "、".join("「%s」" % w for w in 语气[:3]))

    if 全.count("！") + 全.count("!") >= max(3, 条数 * 0.2):
        习惯.append("爱用感叹号")
    if 全.count("…") >= max(2, 条数 * 0.15):
        习惯.append("爱用省略号")
    if 全.count("~") + 全.count("～") >= max(2, 条数 * 0.15):
        习惯.append("爱用波浪号")
    有句号 = sum(1 for t in 话们 if t.endswith("。"))
    if 条数 >= 12 and 有句号 / float(条数) < 0.15:
        习惯.append("句末常常不加句号")

    您 = 全.count("您")
    你 = 全.count("你")
    if 您 >= 3 and 您 > 你:
        习惯.append("对人用「您」")
    elif 你 >= 5:
        习惯.append("直接叫「你」")

    emoji = len(re.findall(r"[\U0001F300-\U0001FAFF\u2600-\u27BF]", 全))
    if emoji >= max(2, 条数 * 0.1):
        习惯.append("爱带表情")

    if 习惯:
        出.append("说话习惯：" + "；".join(习惯))
    return 出


def 提炼(账号, 场="", 对=""):
    r"""按回退阶梯提炼。→ {"档": 格/对象/场景/全局, "句数": n, "条们": [...]}"""
    样们 = 看(账号)
    总 = len(样们)
    出 = {"档": "全局", "句数": 总, "条们": _提炼一段(样们)}

    # ① 本格
    本格 = [s for s in 样们 if s.get("场") == 场 and s.get("对") == 对] if (场 and 对) else []
    if len(本格) >= 门槛["格"]:
        条 = _提炼一段(本格)
        if 条:
            return {"档": "格", "句数": len(本格), "条们": 条}

    # ② 同对象（跨场景）
    同对 = [s for s in 样们 if s.get("对") == 对] if 对 else []
    if len(同对) >= 门槛["对象"]:
        条 = _提炼一段(同对)
        if 条:
            return {"档": "对象", "句数": len(同对), "条们": 条}

    # ③ 同场景（跨对象）
    同场 = [s for s in 样们 if s.get("场") == 场] if 场 else []
    if len(同场) >= 门槛["场景"]:
        条 = _提炼一段(同场)
        if 条:
            return {"档": "场景", "句数": len(同场), "条们": 条}

    # ④ 全局
    return 出


def 说明(果, 场="", 对=""):
    r"""回退到全局/场景时，给模型一句场合说明 —— 这一句比多调十次参数有用。"""
    档 = (果 or {}).get("档")
    场名 = {"闲": "闲着", "忙": "手上正忙", "夜": "夜里"}.get(场, "")
    对名 = {"生": "一个不太熟的人", "熟": "熟人", "亲": "亲近的人"}.get(对, "")
    if 档 == "格":
        return ""
    头 = "你现在%s" % 场名 if 场名 else ""
    if 对名:
        头 += ("，对面是%s" % 对名) if 头 else ("对面是%s" % 对名)
    if not 头:
        return ""
    料 = {"对象": "这些样本是他对同一类人说话时留下的",
          "场景": "这些样本是他在同样处境下说话时留下的",
          "全局": "这些样本是他在**别的场合**（多半是忙的时候、对生人）留下的"}.get(档, "")
    return ("【场合提醒】%s。%s，**别照搬** —— "
            "这个场合下他会%s。" % (头, 料, _场合调(场, 对)))


def _场合调(场, 对):
    句 = []
    if 场 == "夜":
        句.append("更松、句子更长、更愿意说心里话")
    elif 场 == "忙":
        句.append("更短、更急、不展开")
    if 对 == "亲":
        句.append("更不客气、更随便、会损人也会认软")
    elif 对 == "生":
        句.append("更收着、更客气、但话不多")
    return "；".join(句) or "跟平时差不多"


# ────────────────────────── 同步到档案 ──────────────────────────

def 同步(账号):
    r"""把全局提炼写进档案「语言指纹」最前面（提示词只取前 2 条）。"""
    import 档案 as D
    果 = 提炼(账号)
    条们 = 果["条们"]
    if not 条们:
        return 0, "还没学出什么（样本不够）"
    档 = D.读(账号)
    if not (档.get("对象") or {}).get("代号"):
        return 0, "这个人还没有档案"
    栏 = ((档.get("栏") or {}).get("语言指纹") or {}).get("条目")
    if 栏 is None:
        return 0, "档案里没有语言指纹这一栏"

    旧 = [x for x in 栏 if str(x.get("问") or "") == "学话"]
    栏[:] = [x for x in 栏 if str(x.get("问") or "") != "学话"]
    新条 = [{"文": t, "来源": "观察", "问": "学话",
             "于": time.strftime("%Y-%m-%d %H:%M:%S")} for t in 条们]
    栏[:0] = 新条
    D.写(档)
    d = _读(账号)
    d["上次同步"] = int(time.time())
    _写(账号, d)
    return len(新条), "写进去 %d 条（替掉旧的 %d 条）" % (len(新条), len(旧))


def 够了吗(账号):
    d = _读(账号)
    return len(d.get("样") or []) - int(d.get("上次同步") or 0) >= 下次同步条数


def 回填():
    r"""把历史会话里真人自己说的话喂一遍，**并尽量补上场合标签**。

    时间戳能推场景；关系卡能推对象。推不出的就留空，只计入全局。
    """
    import 关系
    会路 = os.path.join(本, "数据", "真人", "会话.json")
    if not os.path.isfile(会路):
        return 0, 0
    会们 = json.load(open(会路, encoding="utf-8"))
    import 此刻
    场景对 = {"干活中": "忙", "刚下工": "忙", "饭点": "忙", "收摊": "忙", "被叫走": "忙",
            "闲时": "闲", "夜里": "夜"}
    记了 = 0
    人 = {}
    for 会 in 会们.values():
        甲, 乙 = str(会.get("甲") or ""), str(会.get("乙") or "")
        for m in (会.get("消息") or []):
            谁 = str(m.get("谁") or "")
            if 谁 not in (甲, 乙):
                continue
            话 = str(m.get("话") or "").strip()
            if len(话) < 2:
                continue
            他 = 乙 if 谁 == 甲 else 甲
            # 场景：按消息时间
            场 = ""
            try:
                时 = m.get("时") or m.get("于")
                if isinstance(时, (int, float)):
                    场 = 场景对.get(此刻.按钟点(time.localtime(int(时)).tm_hour), "闲")
                elif isinstance(时, str) and len(时) >= 13:
                    场 = 场景对.get(此刻.按钟点(int(时[11:13])), "闲")
            except Exception:
                场 = ""
            # 对象：他（角色）跟"谁"的关系
            对 = ""
            try:
                卡 = 关系.取卡(关系.读(他), 谁) or {}
                类 = str(卡.get("类型") or "")
                亲 = float(卡.get("亲疏") or 0)
                if 类 in ("家人", "亲人", "父母", "子女") or 亲 >= 7.0:
                    对 = "亲"
                elif 类 in ("好友", "朋友", "熟人") or 亲 >= 3.5:
                    对 = "熟"
                elif 卡:
                    对 = "生"
            except Exception:
                对 = ""
            if 记(谁, 话, 场=场, 对=对):
                记了 += 1
                人.setdefault(谁, 0)
                人[谁] += 1
    同步了 = 0
    for 谁 in 人:
        n, _ = 同步(谁)
        if n:
            同步了 += 1
    return 记了, 同步了


