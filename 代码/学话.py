"""学话.py —— 从本人说的话里学语言指纹（v0.2.0，2026-11-14）

## v0.2 改了什么
```
  v0.1：所有样本混在一起，提炼出一个指纹。
        实测线上 59 句里 49 句是"忙×生人"，于是所有人听到的
        都是"他对陌生人、在忙的时候"的说话方式。夜里、对亲人，全错。
  v0.2：样本打两个标签（场景 / 对象），按格子提炼，并且有**回退阶梯**：

        ① 本格 ≥ 20 句   → 用本格
        ② 同对象 ≥ 30 句 → 用同对象（跨场景）
        ③ 同场景 ≥ 30 句 → 用同场景（跨对象）
        ④ 都不够        → 全局 + 一句"场合说明"

        第 ④ 条那句说明是重点：告诉模型"这是他在别的场合说话的样子，别照搬"。
```

## 提炼什么（同 v0.1，仍是数出来的）
```
口头禅    2–4 字片段，跨 ≥3 条消息、总 ≥4 次
语气词    吧/呢/啊/嘛/哦/呗/咯
句长      平均 + P10/P90（分布，不只是均值）
标点      感叹号 / 省略号 / 波浪号 / 句末句号
称呼      您 / 你
表情      emoji
```

## 两个坑（v0.1 就有的，注释保留）
```
① 档案「语言指纹」在提示词里只取前 2 条 → 学到的必须插最前
② 档案.加 的来源只认 问/旁人/导入/观察/不知道/生成 → 学出来的用"观察"
```

用法：
```
  python -X utf8 学话.py --自检
  python -X utf8 学话.py --回填
"""
