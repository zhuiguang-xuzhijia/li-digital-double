# -*- coding: utf-8 -*-
"""后果学习.py —— 让策略头不再模仿我，而是从后果里学（v0.1.0，2026-11-14）

## 现在的问题
```
  策略头学的是我手写的老师：
        完整度低 → 说短
  那不是它学到的，是我告诉它的。它学得再准，也只是在复制我的判断。
```

## 要变成什么
```
  它按某种行为做，然后观察后果（对方接不接、投入多少），
  从"哪种行为在哪种状态下后果更好"里，自己反推出策略。
```

## 这是个什么数学问题
```
  上下文赌博机（contextual bandit）：
      上下文 x = [状态5, 情境5]
      动作   a = [长度档, 展开, 反问]
      奖励   r = 对方后果

  难点：只能看到"我选的那个动作"的奖励，看不到没选的。
  → 必须探索（ε-greedy），否则永远不知道别的动作好不好。
  → 学一个线性奖励模型 r ≈ θ·[x, a]，然后对每个 x 取 argmax_a。
```

## 为什么先写它、先不接
```
  线上现在一条 (状态, 情境, 行为, 后果) 日志都没有。
  没有数据，谈"从后果学"是空话。

  所以这一步做两件事：
      ① 把学习器写对 —— 用已知真实奖励的合成数据验证它能不能反推出来
      ② 验证通过后再接线上日志（那是下一步）
```

用法：
```
  python3 后果学习.py --自检
  python3 后果学习.py            # 合成实验：能不能从日志里反推出真策略
"""
import itertools
import json
import math
import os
import random
import statistics
import sys

本 = os.path.dirname(os.path.abspath(__file__))
数据 = os.path.join(本, "数据", "策略日志.json")

# 动作空间：长度 4 档 × 展开 2 × 反问 2 = 16
长度档 = [8, 15, 25, 35]
动作们 = [(L, 展, 问) for L in 长度档 for 展 in (0, 1) for 问 in (0, 1)]

维 = ["完整度", "唯一性", "连续性", "被承认", "可撤销性"]


def 动作向量(a):
    return [a[0] / 35.0, float(a[1]), float(a[2])]


def 情境特征(状态, 情):
    r"""只含上下文，不含动作 —— 每个动作有自己的权重。"""
    return [1.0] + [状态[k] for k in 维] + list(情)


def 特征(状态, 情, a):
    r"""★ 2026-11-14：加了「状态 × 动作」的交叉项。

    只用线性项时，模型只能学出长度固定多少最好，
    学不出状态好时说长、状态差时说短 ——
    因为最优长度依赖状态，那是**交互**，不是加法。

    实测：纯线性时学到 0.563，比老师 0.769 还差，甚至不如随机 0.596。
    """
    基 = [状态[k] for k in 维] + list(情) + 动作向量(a)
    交 = []
    for k in 维:
        for j in range(3):
            交.append(状态[k] * 动作向量(a)[j])
    return 基 + 交


# ────────────────────────── 学习器 ──────────────────────────

def 拟合(日志, 岭=1e-2):
    r"""★ 每个动作一套权重，只用"实际做了这个动作"的样本。

    为什么不是一套全局权重：
      奖励对长度是"尖的"（最优长度落在某一点，两边都掉），
      一个线性模型只能给一个全局最优，学不出"状态好时该长、状态差时该短"。
      实测全局模型 0.692，比老师的 0.769 还差。

    每动作建模的代价：每个动作至少要十几条样本，所以必须真的探索。
    """
    出 = {}
    for a in 动作们:
        子 = [条 for 条 in 日志 if tuple(条["a"]) == a]
        if len(子) < 8:
            continue
        n = len(子[0]["c"])
        A = [[0.0] * n for _ in range(n)]
        b = [0.0] * n
        for 条 in 子:
            x = 条["c"]
            for i in range(n):
                b[i] += x[i] * 条["r"]
                for j in range(n):
                    A[i][j] += x[i] * x[j]
        for i in range(n):
            A[i][i] += 岭 * len(子)
        for i in range(n):
            p = max(range(i, n), key=lambda k: abs(A[k][i]))
            if abs(A[p][i]) < 1e-12:
                continue
            A[i], A[p] = A[p], A[i]
            b[i], b[p] = b[p], b[i]
            d = A[i][i]
            for j in range(i, n):
                A[i][j] /= d
            b[i] /= d
            for k in range(n):
                if k == i:
                    continue
                f = A[k][i]
                if f == 0:
                    continue
                for j in range(i, n):
                    A[k][j] -= f * A[i][j]
                b[k] -= f * b[i]
        出[a] = b
    return 出


def 打分(θ们, 状态, 情, a):
    w = θ们.get(tuple(a))
    if w is None:
        return -1.0                     # 没数据支撑的动作不选
    x = 情境特征(状态, 情)
    return sum(a1 * a2 for a1, a2 in zip(w, x))


def 策略(θ们, 状态, 情):
    有 = [a for a in 动作们 if 打分(θ们, 状态, 情, a) >= 0]
    if not 有:
        return 老师(状态, 情)
    return max(有, key=lambda a: 打分(θ们, 状态, 情, a))


def 老师(状态, 情):
    r"""现在线上的老师：状态低 → 说短、不展开、不反问。"""
    完, 认 = 状态["完整度"], 状态["被承认"]
    L = 6 + 34 * (完 * 0.6 + 状态["连续性"] * 0.4)
    档 = min(长度档, key=lambda z: abs(z - L))
    return (档, 1 if (完 > 0.5 and 认 > 0.5) else 0, 1 if (认 > 0.6 and 完 > 0.4) else 0)


def 采集(真奖, 条数=4000, ε=0.65, 种子=7):
    r"""ε-greedy 采日志：大部分按老师做，一部分乱试。"""
    随 = random.Random(种子)
    日志 = []
    for _ in range(条数):
        状 = {k: 随.uniform(0.05, 0.95) for k in 维}
        情 = [随.choice([1, 0, 0]), 随.choice([0, 1, 0]), 随.choice([0, 0, 1]),
              随.choice([1.0, 0.6, 0.2]), 随.uniform(0, 1)]
        a = 随.choice(动作们) if 随.random() < ε else 老师(状, 情)
        r = 真奖(状, 情, a) + 随.gauss(0, 0.05)
        日志.append({"x": 特征(状, 情, a), "c": 情境特征(状, 情),
                     "r": max(0.0, min(1.0, r)), "状": 状, "情": 情, "a": a})
    return 日志


def 评测(θ, 真奖, 种子=99, 条数=200):
    r"""学到的策略 vs 老师 vs 随机 vs 真实最优。"""
    随 = random.Random(种子)
    组 = {"学到": [], "老师": [], "随机": [], "最优": []}
    for _ in range(条数):
        状 = {k: 随.uniform(0.05, 0.95) for k in 维}
        情 = [随.choice([1, 0, 0]), 随.choice([0, 1, 0]), 随.choice([0, 0, 1]),
              随.choice([1.0, 0.6, 0.2]), 随.uniform(0, 1)]
        组["学到"].append(真奖(状, 情, 策略(θ, 状, 情)))
        组["老师"].append(真奖(状, 情, 老师(状, 情)))
        组["随机"].append(真奖(状, 情, 随.choice(动作们)))
        组["最优"].append(max(真奖(状, 情, a) for a in 动作们))
    return {k: round(statistics.mean(v), 3) for k, v in 组.items()}


# ────────────────────────── 合成实验 ──────────────────────────

def 真奖A(状, 情, a):
    r"""真实规则：状态好时，说长、展开、反问都更好；状态差时反过来。

    注意：这条规则**和老师不完全一样** ——
    老师在"被承认低"时不反问，但真规则里"唯一性高"时还是会反问。
    学习器如果只抄老师，就发现不了这一条。
    """
    好 = 状["完整度"] * 0.5 + 状["被承认"] * 0.3 + 状["连续性"] * 0.2
    L, 展, 问 = a
    长合 = 1.0 - abs(L - (8 + 27 * 好)) / 30.0
    展合 = 1.0 if (展 and 好 > 0.45) or (not 展 and 好 <= 0.45) else 0.0
    问合 = 1.0 if (问 and (好 > 0.5 or 状["唯一性"] > 0.8)) or (not 问 and 好 <= 0.5) else 0.0
    return max(0.0, min(1.0, 0.5 * 长合 + 0.3 * 展合 + 0.2 * 问合))


def 真奖B(状, 情, a):
    r"""另一种真实规则：说长反而是负担（对方话少）。用来测学习器不是只会一套。"""
    L, 展, 问 = a
    好 = 状["完整度"]
    长合 = 1.0 - abs(L - (32 - 22 * (1 - 好))) / 30.0
    展合 = 1.0 if (展 and 好 > 0.6) else (0.0 if 展 else 1.0)
    问合 = 1.0 if (问 and 情[4] < 0.6) else (0.0 if 问 else 1.0)
    return max(0.0, min(1.0, 0.5 * 长合 + 0.25 * 展合 + 0.25 * 问合))


def 主():
    print("=" * 62)
    print("合成实验：能不能从「自己试出来的日志」反推出更好的策略")
    print("=" * 62)
    for 名, 真奖 in (("A（状态好该展开）", 真奖A), ("B（话少该短）", 真奖B)):
        print()
        print("  真实规则 %s" % 名)
        日志 = 采集(真奖, 条数=4000, ε=0.65)
        θ = 拟合(日志)
        果 = 评测(θ, 真奖)
        print("    采样 %d 条（ε=0.65 探索）" % len(日志))
        print("    学到 %.3f　老师 %.3f　随机 %.3f　最优 %.3f" % (
            果["学到"], 果["老师"], 果["随机"], 果["最优"]))
        提 = (果["学到"] - 果["老师"]) / max(1e-9, 果["最优"] - 果["老师"]) * 100
        print("    补上了老师到最优之间的 %.0f%%" % max(0.0, 提))
    print()
    print("  注意：老师不是最优。学习器如果只抄老师，到不了「最优」那一栏。")


def 自检():
    好 = 总 = 0

    def 验(名, 条, 注=""):
        nonlocal 好, 总
        总 += 1
        好 += 1 if 条 else 0
        print("  %s %-46s %s" % ("✅" if 条 else "❌", 名, str(注)[:44]))

    验("动作空间 16 个", len(动作们) == 16, len(动作们))
    验("特征长度 28（含交叉项）",
       len(特征({k: 0.5 for k in 维}, [1, 0, 0, 1.0, 0.5], 动作们[0])) == 13 + 15,
       len(特征({k: 0.5 for k in 维}, [1, 0, 0, 1.0, 0.5], 动作们[0])))
    验("情境特征长度 11", len(情境特征({k: 0.5 for k in 维}, [1, 0, 0, 1.0, 0.5])) == 11)

    随 = random.Random(1)
    真 = lambda 状, 情, a: 0.7 * a[0] / 35.0 + 0.2 * a[1] + 0.1 * a[2]
    日志 = 采集(真, 条数=400, ε=0.5, 种子=3)
    验("采到日志", len(日志) == 400)
    θ = 拟合(日志)
    验("拟合出每动作权重", isinstance(θ, dict) and len(θ) >= 8, len(θ) if θ else 0)
    验("每个动作权重长度对", all(len(w) == 11 for w in (θ or {}).values()))
    状 = {k: 0.5 for k in 维}
    情 = [1, 0, 0, 1.0, 0.5]
    a = 策略(θ, 状, 情)
    验("学出「越长越好」", a[0] == 35, a)
    验("两条规则下都能学", 拟合(采集(真奖B, 条数=600)) is not None)
    # 学习器不该等于老师 —— 要在「最优≠老师」的规则下测（A 规则就是）
    θA = 拟合(采集(真奖A, 条数=800, 种子=5))
    不同 = 0
    for 完 in (0.1, 0.4, 0.8):
        for 认 in (0.1, 0.5, 0.9):
            状2 = {k: 完 for k in 维}
            状2["被承认"] = 认
            if 策略(θA, 状2, 情) != 老师(状2, 情):
                不同 += 1
    验("策略与老师有分歧（真的在学）", 不同 >= 2, "%d/9 个状态不同" % 不同)

    print("\n  结果：%d 过 / %d 不过" % (好, 总 - 好))
    return 0 if 好 == 总 else 1


if __name__ == "__main__":
    sys.exit(自检() if "--自检" in sys.argv else (主() or 0))
