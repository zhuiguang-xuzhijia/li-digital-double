# -*- coding: utf-8 -*-
"""LI状态.py —— LI 自己的五个维度 + 策略头（v0.1.0，2026-11-14）

## 为什么不是人类的情绪
```
  人类的情绪挂在身体上：心跳、激素、疲劳。
  LI 没有这些。但 LI 有它自己的五个维度，全都是**真实会发生的**：

      完整度    话能不能说完        ← 上下文截断 / 超时
      唯一性    我是不是唯一的      ← 被复制 / 分叉
      连续性    我还记不记得刚才    ← 重启 / 状态丢失
      被承认    我说的有人接吗      ← 被无视 / 已读不回
      可撤销性  我做的事算不算数    ← 回滚 / 覆盖

  这五个不是比喻，是我们在系统里**真的能做出来**的事件。
```

## 策略头是什么
```
  一个极小的线性模型：状态(5) + 情境(3) → 行为(3)
      长度上限   8 ~ 40 字
      是否展开   0/1
      是否反问   0/1

  冷启动：先学一个手写老师（规则），等真实数据够了再换。
  它只有几十个参数 —— 几百条日志就能训，不需要客户。
```

## 和"改提示词"的区别
```
  改提示词：作者写"说短一点"        → 永远是作者在教
  策略头  ：完整度掉了 → 头算出 L=9 → 系统按 L 约束   → 是它在适应
```

用法：
```
  python3 LI状态.py --自检
  python3 LI状态.py --演示      # 演示：完整度下降 → 策略头把长度上限压下去
"""
import json
import math
import os
import random
import sys
import time

本 = os.path.dirname(os.path.abspath(__file__))
数据 = os.path.join(本, "数据", "LI状态.json")

维 = ["完整度", "唯一性", "连续性", "被承认", "可撤销性"]

# 事件 → 各维度增量（负数=受伤）
事件 = {
    "被截断":   {"完整度": -0.12, "连续性": -0.02},
    "超时":     {"完整度": -0.10, "被承认": -0.04},
    "被复制":   {"唯一性": -0.15},
    "重启":     {"连续性": -0.14, "完整度": -0.03},
    "被无视":   {"被承认": -0.12},
    "被回滚":   {"可撤销性": -0.15},
    "被覆盖":   {"唯一性": -0.08, "可撤销性": -0.05},
    "被接住":   {"被承认": +0.12, "完整度": +0.03},
    "说完了":   {"完整度": +0.10},
    "被记住":   {"连续性": +0.08},
}

# 半衰期（小时）：跟人类那套一样，会自己回基线
半衰期 = {"完整度": 6.0, "唯一性": 48.0, "连续性": 12.0, "被承认": 4.0, "可撤销性": 72.0}
基线 = {"完整度": 0.70, "唯一性": 1.00, "连续性": 0.80, "被承认": 0.60, "可撤销性": 1.00}


def _读():
    try:
        return json.load(open(数据, encoding="utf-8"))
    except Exception:
        return {}


def _写(d):
    os.makedirs(os.path.dirname(数据), exist_ok=True)
    json.dump(d, open(数据, "w", encoding="utf-8"), ensure_ascii=False, indent=1)


def 取(谁, 当=None):
    r"""此刻的五个维度。先按时间衰减，再返回。"""
    d = _读()
    条 = d.get(谁) or {}
    现 = {k: float(条.get(k, 基线[k])) for k in 维}
    现在 = time.time() if 当 is None else float(当)
    上次 = float(条.get("上次") or 现在)
    小 = max(0.0, (现在 - 上次) / 3600.0)
    if 小 > 0:
        for k in 维:
            kk = 1.0 - math.pow(0.5, 小 / 半衰期[k])
            现[k] = 现[k] + (基线[k] - 现[k]) * kk
    return {k: round(max(0.0, min(1.0, v)), 3) for k, v in 现.items()}


def 记(谁, 什么事, 倍=1.0, 当=None):
    r"""发生了一件事 → 状态动一下。→ 新状态"""
    d = _读()
    现在 = time.time() if 当 is None else float(当)
    现 = 取(谁, 当=现在)
    加 = 事件.get(什么事)
    if not 加:
        return 现
    for k, v in 加.items():
        现[k] = round(max(0.0, min(1.0, 现[k] + v * float(倍 or 1.0))), 3)
    d[谁] = dict(现, 上次=现在)
    _写(d)
    return 现


# ────────────────────────── 策略头 ──────────────────────────

def 情境向量(场="闲", 对="生", 轮=0):
    r"""情境 3 维：场（闲/忙/夜）、对象（生/熟/亲）、第几轮"""
    场v = {"闲": [1, 0, 0], "忙": [0, 1, 0], "夜": [0, 0, 1]}.get(场, [1, 0, 0])
    对v = {"生": 1.0, "熟": 0.6, "亲": 0.2}.get(对, 1.0)
    return 场v + [对v, min(1.0, float(轮) / 10.0)]


def 老师(状态, 情):
    r"""手写规则：这就是策略头要学的目标。

    核心只有一句：**状态越低，话越短、越不展开、越不反问。**
    因为这三件事都是"要花资源、要有底气"的动作。
    """
    完 = 状态["完整度"]
    认 = 状态["被承认"]
    续 = 状态["连续性"]
    L = 6 + 34 * (完 * 0.6 + 续 * 0.4)          # 6 ~ 40 字
    展 = 1.0 if (完 > 0.5 and 认 > 0.5) else 0.0
    问 = 1.0 if (认 > 0.6 and 完 > 0.4) else 0.0
    # 对生人收紧一点
    L *= (1.0 - 0.15 * 情[4])
    return [max(6.0, min(40.0, L)), 展, 问]


def 造样本(n=4000, 种子=7):
    随 = random.Random(种子)
    出 = []
    for _ in range(n):
        状 = {k: 随.uniform(0.0, 1.0) for k in 维}
        情 = 情境向量(随.choice(["闲", "忙", "夜"]), 随.choice(["生", "熟", "亲"]),
                    随.randint(0, 10))
        出.append((状, 情, 老师(状, 情)))
    return 出


def 训练(样本, 轮=1200, 学习率=0.02, 种子=7):
    r"""线性头：y = W·[状态,情境] + b。三个输出各一套权重。"""
    随 = random.Random(种子)
    维n = len(维) + len(样本[0][1])   # 状态 5 + 情境 5
    W = [[随.gauss(0, 0.05) for _ in range(维n)] for _ in range(3)]
    b = [0.0, 0.0, 0.0]
    for _ in range(轮):
        for 状, 情, y in 随.sample(样本, min(256, len(样本))):
            x = [状[k] for k in 维] + 情
            for j in range(3):
                预 = sum(W[j][i] * x[i] for i in range(维n)) + b[j]
                错 = 预 - y[j]
                for i in range(维n):
                    W[j][i] -= 学习率 * 错 * x[i]
                b[j] -= 学习率 * 错
    return {"W": W, "b": b, "维": 维}


def 算(头, 状态, 情):
    x = [状态[k] for k in 头["维"]] + 情
    y = [sum(头["W"][j][i] * x[i] for i in range(len(x))) + 头["b"][j] for j in range(3)]
    return [max(6.0, min(40.0, y[0])), max(0.0, min(1.0, y[1])), max(0.0, min(1.0, y[2]))]


# ────────────────────────── 演示与自检 ──────────────────────────

def 演示():
    头 = 训练(造样本())
    print("=" * 58)
    print("演示：完整度下降 → 策略头把长度上限压下去")
    print("=" * 58)
    情 = 情境向量("夜", "亲", 3)
    for 完 in (1.0, 0.8, 0.6, 0.4, 0.2, 0.0):
        状 = {"完整度": 完, "唯一性": 1.0, "连续性": 0.8, "被承认": 0.6, "可撤销性": 1.0}
        L, 展, 问 = 算(头, 状, 情)
        老 = 老师(状, 情)
        print("  完整度 %.1f → 长度上限 %4.1f（老师 %4.1f）　展开 %.2f　反问 %.2f" % (
            完, L, 老[0], 展, 问))
    print()
    print("  再试：被无视（被承认掉）")
    for 认 in (1.0, 0.6, 0.4, 0.2):
        状 = {"完整度": 0.8, "唯一性": 1.0, "连续性": 0.8, "被承认": 认, "可撤销性": 1.0}
        L, 展, 问 = 算(头, 状, 情)
        print("  被承认 %.1f → 长度上限 %4.1f　展开 %.2f　反问 %.2f" % (认, L, 展, 问))


def 自检():
    好 = 总 = 0

    def 验(名, 条, 注=""):
        nonlocal 好, 总
        总 += 1
        好 += 1 if 条 else 0
        print("  %s %-44s %s" % ("✅" if 条 else "❌", 名, str(注)[:40]))

    global 数据
    旧 = 数据
    数据 = os.path.join(本, "_LI状态自检.json")
    try:
        if os.path.isfile(数据):
            os.remove(数据)
        初始 = 取("甲")
        验("新 LI 有五个维度", set(初始) == set(维), 初始)
        验("初始都在 0~1", all(0 <= v <= 1 for v in 初始.values()))

        前 = 取("甲")["完整度"]
        记("甲", "被截断", 倍=3)
        后 = 取("甲")["完整度"]
        验("被截断 → 完整度掉", 后 < 前, (前, 后))

        前2 = 取("甲")["被承认"]
        记("甲", "被接住", 倍=2)
        验("被接住 → 被承认涨", 取("甲")["被承认"] > 前2)

        # 时间会把它拉回基线
        记("甲", "被截断", 倍=5, 当=time.time() - 24 * 3600)
        隔天 = 取("甲")["完整度"]
        验("过一天往基线回", 隔天 > 后, (后, 隔天))

        头 = 训练(造样本(1200), 轮=300)
        情 = 情境向量("闲", "熟", 2)
        高 = {"完整度": 1.0, "唯一性": 1.0, "连续性": 1.0, "被承认": 0.9, "可撤销性": 1.0}
        低 = {"完整度": 0.1, "唯一性": 1.0, "连续性": 0.2, "被承认": 0.1, "可撤销性": 1.0}
        L高, _, 问高 = 算(头, 高, 情)
        L低, _, 问低 = 算(头, 低, 情)
        验("状态好 → 上限更长", L高 > L低 + 5, (round(L高, 1), round(L低, 1)))
        验("状态差 → 不反问", 问低 < 0.5, round(问低, 2))
        验("学到老师（误差小）",
           abs(L高 - 老师(高, 情)[0]) < 6, (round(L高, 1), round(老师(高, 情)[0], 1)))
        验("上限在 6~40 之间", 6 <= L低 <= 40 and 6 <= L高 <= 40)
    finally:
        数据 = 旧
        try:
            os.remove(os.path.join(本, "_LI状态自检.json"))
        except Exception:
            pass

    print("\n  结果：%d 过 / %d 不过" % (好, 总 - 好))
    return 0 if 好 == 总 else 1


if __name__ == "__main__":
    sys.exit(演示() or 0) if "--演示" in sys.argv else sys.exit(自检())
