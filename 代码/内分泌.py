# -*- coding: utf-8 -*-
"""内分泌.py —— 慢变量：皮质醇/多巴胺/睾酮（v0.1.0，2026-11-13）

## 为什么要有这个
```
  情绪（S）是这一轮的，几分钟就过去了。
  内分泌是**几小时到几天**的底色：连着被骂三天，皮质醇会一直挂着，
  于是同一个他，说话会越来越冲、越来越往坏处想。
  没有这一层，"越聊越像活的"就只能靠模型即兴。
```

## 三个旋钮（0–1）
```
  皮质醇  压力荷尔蒙。高 → 绷着、一点就着、专想坏事、话变短
  多巴胺  奖赏。高 → 有劲、愿意多说、看什么都还行
  睾酮    对抗性。高 → 更硬、更不肯让、被顶了会顶回去
```

## 怎么动
```
  被骂 / 吵起来     皮质醇 +0.06×强度   睾酮 +0.03×强度   多巴胺 -0.02
  被夸 / 被需要     多巴胺 +0.05×强度   皮质醇 -0.02
  被敷衍 / 踩禁忌    皮质醇 +0.04        多巴胺 -0.03
  平静地聊          多巴胺 +0.01
  时间流逝          **全部向基线回落**：半衰期 皮质醇6h / 多巴胺3h / 睾酮12h
```

## 存哪
```
  数据/内分泌.json ： {代号: {皮质醇, 多巴胺, 睾酮, 基线{...}, 上次}}
  读的时候先按"上次到现在过了多久"衰减一遍 —— 不衰减的话，一年前的怒气会留到今天
```

用法：
```
  python -X utf8 内分泌.py --自检     # 含"连骂三天"的曲线
"""
import json
import math
import os
import sys
import time

本 = os.path.dirname(os.path.abspath(__file__))
数据 = os.path.join(本, "数据", "内分泌.json")

默认基线 = {"皮质醇": 0.40, "多巴胺": 0.50, "睾酮": 0.50}
半衰期 = {"皮质醇": 10.0, "多巴胺": 3.0, "睾酮": 12.0}   # 小时

# 事件 → 各旋钮的增量（再乘强度）
事件 = {
    "被骂": {"皮质醇": +0.09, "睾酮": +0.04, "多巴胺": -0.05},
    "被夸": {"多巴胺": +0.06, "皮质醇": -0.03},
    "被敷衍": {"皮质醇": +0.05, "多巴胺": -0.04},
    "踩禁忌": {"皮质醇": +0.10, "睾酮": +0.05},
    "平静": {"多巴胺": +0.01},
}


def _读():
    try:
        return json.load(open(数据, encoding="utf-8"))
    except Exception:
        return {}


def _写(d):
    os.makedirs(os.path.dirname(数据), exist_ok=True)
    json.dump(d, open(数据, "w", encoding="utf-8"), ensure_ascii=False, indent=1)


def _回(值, 基, 小时间隔):
    r"""按半衰期回归基线。"""
    if 小时间隔 <= 0:
        return 值
    k = 1.0 - math.pow(0.5, 小时间隔 / 半衰期.get("皮质醇", 6.0))
    return 值 + (基 - 值) * k


def 取(账号, 当=None):
    r"""此刻的内分泌。**先按时间衰减**，再返回。

    当：把"现在"当成某个时刻（自检/回放用），不传就是真的现在。
    """
    d = _读()
    条 = d.get(账号) or {}
    基 = dict(默认基线)
    基.update(条.get("基线") or {})
    现 = {k: float(条.get(k, 基[k])) for k in 默认基线}
    现在 = time.time() if 当 is None else float(当)
    上次 = float(条.get("上次") or 现在)
    小时间隔 = max(0.0, (现在 - 上次) / 3600.0)
    if 小时间隔 > 0:
        for k in 现:
            # 每个旋钮自己半衰期
            kk = 1.0 - math.pow(0.5, 小时间隔 / 半衰期[k])
            现[k] = 现[k] + (基[k] - 现[k]) * kk
    现 = {k: round(max(0.0, min(1.0, v)), 3) for k, v in 现.items()}
    现["基线"] = 基
    return 现


def 记(账号, 什么, 强度=0.6, 当=None):
    r"""发生了一件事 → 内分泌动一下。→ 新的状态"""
    d = _读()
    现在 = time.time() if 当 is None else float(当)
    现 = 取(账号, 当=现在)
    基 = 现.pop("基线", dict(默认基线))
    加 = 事件.get(什么)
    if not 加:
        return 现
    强 = max(0.0, min(1.0, float(强度 or 0.6)))
    for k, v in 加.items():
        现[k] = max(0.0, min(1.0, 现[k] + v * 强))
    d[账号] = dict(现, 基线=基, 上次=现在)
    _写(d)
    return 现


def 说(现):
    r"""内分泌翻译成一句人话（给提示词和界面用）。"""
    皮 = float(现.get("皮质醇") or 0)
    多 = float(现.get("多巴胺") or 0)
    睾 = float(现.get("睾酮") or 0)
    句 = []
    if 皮 >= 0.7:
        句.append("绷得很紧：一点就着，容易往坏处想")
    elif 皮 <= 0.25:
        句.append("很松：心里没事压着")
    if 多 >= 0.7:
        句.append("有劲，愿意多说两句")
    elif 多 <= 0.25:
        句.append("提不起劲：话会少，也懒得接梗")
    if 睾 >= 0.7:
        句.append("硬：被顶了会顶回去，不肯让")
    elif 睾 <= 0.25:
        句.append("软：不想争，能顺着就顺着")
    return "；".join(句) or "状态平：不紧也不松"


def 判断(现):
    r"""内分泌 → 他这会儿对一句普通问话的**预判**（不是情绪词，是立场）。

    ★ 2026-11-13 实测：只说"绷着"模型不改口；给它一个判断，它才知道往哪走。
    """
    皮 = float(现.get("皮质醇") or 0.4)
    多 = float(现.get("多巴胺") or 0.5)
    睾 = float(现.get("睾酮") or 0.5)
    if 皮 >= 0.7 and 睾 >= 0.65:
        return "你觉得对方是来找茬的：不解释，先顶回去，别让他觉得你好拿捏"
    if 皮 >= 0.7 and 多 <= 0.35:
        return "你觉得什么都不顺：懒得争，也懒得解释，回一句就想撂下"
    if 皮 >= 0.7:
        return "你觉得这事在挑你：先把手上的活说清楚，语气硬一点"
    if 多 >= 0.7:
        return "你觉得这点事不算事：能笑一下就笑一下，多问一句也行"
    if 多 <= 0.3:
        return "你提不起劲：能不接就不接，接也只说事实"
    return ""


def 进提示词(现):
    r"""两行：状态 + 它怎么影响说话。"""
    if not 现:
        return []
    行 = ["【你现在的状态】%s" % 说(现)]
    皮 = float(现.get("皮质醇") or 0)
    多 = float(现.get("多巴胺") or 0)
    影响 = []
    if 皮 >= 0.7:
        影响.append("句子更短、更冲；别客套")
    if 皮 <= 0.25:
        影响.append("句子可以长一点、松一点")
    if 多 <= 0.25:
        影响.append("别主动开玩笑；能不接的话就不接")
    if 多 >= 0.7:
        影响.append("可以主动多说一句")
    if 影响:
        行.append("【这会影响你说话】%s" % "；".join(影响))
    判 = 判断(现)
    if 判:
        行.append("【你现在的判断】%s" % 判)
    return 行


def 自检():
    好 = 总 = 0

    def 验(名, 条, 注=""):
        nonlocal 好, 总
        总 += 1
        好 += 1 if 条 else 0
        print("  %s %-40s %s" % ("✅" if 条 else "❌", 名, str(注)[:40]))

    global 数据
    旧路 = 数据
    数据 = os.path.join(本, "_内分泌自检.json")
    try:
        if os.path.isfile(数据):
            os.remove(数据)
        初始 = 取("甲")
        验("新人默认平", abs(初始["皮质醇"] - 0.40) < 0.01, 初始["皮质醇"])

        # 连骂三天：每 2 小时一次，每次 0.7。★ 时间轴必须往前走，不能跳着传
        起 = time.time() - 72 * 3600
        现 = 初始
        轨迹 = []
        for i in range(36):          # 36 次 × 2 小时 = 72 小时
            现 = 记("甲", "被骂", 0.7, 当=起 + i * 2 * 3600)
            轨迹.append(现["皮质醇"])
        验("连骂三天，皮质醇冲上去", 现["皮质醇"] >= 0.8, 现["皮质醇"])
        验("多巴胺被压下去", 现["多巴胺"] <= 0.45, 现["多巴胺"])
        验("睾酮也上去了", 现["睾酮"] >= 0.6, 现["睾酮"])
        验("曲线是往上走的", 轨迹[-1] > 轨迹[0], (轨迹[0], 轨迹[-1]))

        # 隔 24 小时不理它，应该三个都往回落
        隔天 = 取("甲", 当=起 + 72 * 3600 + 24 * 3600)
        # ★ 注意方向：多巴胺被压到基线**下面**，回落是往**上**回；三个都该离基线更近
        近 = sum(1 for k in 默认基线
                 if abs(隔天[k] - 默认基线[k]) < abs(现[k] - 默认基线[k]))
        验("过一天，三个旋钮都更靠近基线", 近 == 3, (现, 隔天))

        验("说人话：绷着", "绷" in 说({"皮质醇": 0.9, "多巴胺": 0.5, "睾酮": 0.5}))
        验("说人话：提不起劲", "提不起劲" in 说({"皮质醇": 0.4, "多巴胺": 0.1, "睾酮": 0.5}))
        验("说人话：平", "平" in 说(默认基线))
        进 = 进提示词({"皮质醇": 0.9, "多巴胺": 0.2, "睾酮": 0.8})
        验("提示词有状态", any("你现在的状态" in x for x in 进), 进)
        验("提示词有影响", any("这会影响你说话" in x for x in 进), 进)
    finally:
        数据 = 旧路
        try:
            os.remove(os.path.join(本, "_内分泌自检.json"))
        except Exception:
            pass

    print("\n  结果：%d 过 / %d 不过" % (好, 总 - 好))
    return 0 if 好 == 总 else 1


if __name__ == "__main__":
    sys.exit(自检())
