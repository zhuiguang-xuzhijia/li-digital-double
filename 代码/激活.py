# -*- coding: utf-8 -*-
"""激活.py —— 场景叠加 + 概率想起（v0.1.0，2026-11-13）

## 用户的原话
```
  "【场景】+【场景】+【历史】（（场景：看到大暴雨）+（历史：大水冲垮房屋）+（历史：人们颠沛流离））
   其实场景、历史的组合是概率性的，权重是由需求，情绪，内分泌决定的。"
```

## 这里做什么
```
  ① 叠加：此刻的场景（他在收摊）+ 对方这句话引出的刺激场景（"下暴雨了"）+ 情绪底色
  ② 打分：每段历史被想起的分 = 标签重合 × 场景强度 × (0.5+需求) × (1+情绪×同向) × (1+皮质醇×威胁)
  ③ 概率：软最大 → **抽 1–2 段**
  ④ 出词：抽中的那两段进提示词，写成"你此刻想起……"

## 为什么是概率，不是"最相关的那一条"
```
  人不是按索引查记忆的。同一个问题，今天想起这件事，明天想起那件事。
  差别就来自：此刻在哪、这几天什么底色、对方这句话带了什么词。
```

用法：
```
  python -X utf8 激活.py --自检
"""
import math
import random
import re
import sys
import time

# ────────────────────────── 标签 ──────────────────────────
标签词 = {
    "灾难": "水 雨 灾 塌 冲 淹 雪 风 火 震 烧 断",
    "失去": "死 走 没 丢 卖 拆 退 散 离 断",
    "家人": "爸 妈 爹 娘 儿 女 媳 老伴 家 老子 闺女",
    "他人": "邻居 街坊 别人 他们 有人 大伙 人",
    "钱": "钱 块 元 欠 账 赔 借 还 工资 收入",
    "活路": "活 干 摊 铺 手艺 做 挣 上班 接活",
    "病": "病 医 院 手 术 疼 药 伤",
    "面子": "脸 面子 丢人 瞧不起 看轻 低头",
    "感情": "喜欢 爱 想 惦记 心里 难受",
    "冲突": "吵 骂 打 闹 翻脸 顶 凶",
}

效价词 = {
    +1: "救 好 结实 成 考上 结婚 生 涨 赚 帮 谢 值 服 满意 高兴",
    -1: "死 病 塌 冲 淹 丢 欠 赔 吵 骂 打 拆 散 苦 难 冷 没人",
}

威胁词 = "水 灾 塌 冲 淹 死 病 打 吵 欠 赔 拆 走"
对抗词 = "吵 打 骂 顶 凶 争 憋"


def 标签(文):
    t = str(文 or "")
    return {k for k, w in 标签词.items() if any(x in t for x in w.split())}


def 效价(文):
    t = str(文 or "")
    正 = sum(1 for w in 效价词[+1].split() if w in t)
    负 = sum(1 for w in 效价词[-1].split() if w in t)
    if 正 == 负:
        return 0.0
    return round((正 - 负) / float(正 + 负), 3)


def 记段(文):
    """一段历史 → {文, 标签, 效价, 威胁, 对抗}"""
    t = str(文 or "")[:120]
    威 = min(1.0, 0.35 * sum(1 for w in 威胁词.split() if w in t))
    抗 = min(1.0, 0.35 * sum(1 for w in 对抗词.split() if w in t))
    return {"文": t, "标签": 标签(t), "效价": 效价(t), "威胁": 威, "对抗": 抗}


# ────────────────────────── 场景 ──────────────────────────
# 对方一句话能引出的"刺激场景"（叠加在"他此刻在干什么"之上）
刺激 = [
    ("提到下雨/天灾", "雨 暴雨 大水 雪 台风 淹 天灾", ["灾难", "天"]),
    ("提到钱/欠账", "钱 借 欠 还 账 工资 赔", ["钱", "活路"]),
    ("提到家里人", "孩子 儿子 闺女 妈 爸 老婆 老公 媳妇 家里", ["家人"]),
    ("提到身体", "病 医院 疼 手术 药 伤 累", ["病"]),
    ("像是在数落", "慢 破 差 难 烦 催 怎么还 不行", ["冲突", "面子"]),
    ("在夸他", "好 棒 厉害 谢谢 辛苦 服 行", ["感情"]),
]


def 叠(此刻, 对方话, 情绪=0.0):
    r"""此刻的场景 + 对方这句话引出的刺激 → 一串场景（带权重）。"""
    场们 = []
    if 此刻:
        场们.append({"名": 此刻.get("名") or "闲时", "标签": {此刻.get("名") or "闲时"},
                     "强度": 0.7, "来源": "此刻"})
    t = str(对方话 or "")
    for 名, 词, 标 in 刺激:
        if any(w in t for w in 词.split()):
            场们.append({"名": 名, "标签": set(标), "强度": 0.8, "来源": "对方这句"})
    if abs(float(情绪 or 0)) >= 0.4:
        场们.append({"名": "情绪上来了", "标签": {"冲突"} if 情绪 < 0 else {"感情"},
                     "强度": 0.5 + abs(float(情绪)) * 0.4, "来源": "情绪"})
    return 场们


# ────────────────────────── 打分与抽样 ──────────────────────────
需求对标签 = {
    "安全": {"灾难", "失去", "病"},
    "生存": {"钱", "活路", "灾难"},
    "归属": {"家人", "他人", "感情"},
    "尊重": {"面子", "冲突"},
    "掌控": {"活路", "冲突"},
}


def _需求相关(需求, 标):
    if not 标 or not 需求:
        return 0.0
    return max([float(需求.get(k, 0.0)) for k, v in 需求对标签.items() if 标 & v] or [0.0])


def 打分(史段, 场们, 需求, 情绪, 皮):
    重 = 0.0
    for 场 in 场们:
        if 史段["标签"] & 场["标签"]:
            重 += 场["强度"]
    if 重 == 0:
        return 0.02
    需 = _需求相关(需求, 史段["标签"])
    情 = 1.0 + abs(float(情绪 or 0)) * (1.0 if float(情绪 or 0) * 史段["效价"] > 0 else -0.5)
    return max(0.001, 重 * (0.5 + 需) * 情 * (1.0 + float(皮 or 0.4) * 史段["威胁"]))


def 抽(档, 此刻, 对方话, 情绪=0.0, 内分泌=None, 需求=None, 几段=2, 种子=None):
    r"""→ {"场景们": [...], "想起": [段, 段]}（可能空）"""
    史们 = [记段(x.get("文") or "") for x in
            (((档 or {}).get("栏") or {}).get("历史") or {}).get("条目") or []]
    史们 = [x for x in 史们 if x["文"] and x["标签"]]
    if not 史们:
        return {"场景们": [], "想起": []}
    场们 = 叠(此刻, 对方话, 情绪)
    皮 = float((内分泌 or {}).get("皮质醇") or 0.4)
    分们 = [打分(x, 场们, 需求 or {}, 情绪, 皮) for x in 史们]
    最大 = max(分们)
    权 = [math.exp((v - 最大) * 1.2) for v in 分们]
    总 = sum(权)
    p = [w / 总 for w in 权]

    随机 = random.Random(种子 if 种子 is not None else
                         (hash(str(对方话)) ^ int(time.time() // 60)))
    出, 池 = [], list(range(len(史们)))
    for _ in range(min(int(几段 or 2), len(史们))):
        if not 池:
            break
        权2 = [p[i] for i in 池]
        总2 = sum(权2)
        if 总2 <= 0:
            break
        针 = 随机.random() * 总2
        累 = 0.0
        for k, i in enumerate(池):
            累 += 权2[k]
            if 针 <= 累:
                出.append(史们[i])
                池.pop(k)
                break
    return {"场景们": [{"名": x["名"], "强度": x["强度"]} for x in 场们], "想起": 出}


def 进提示词(想起们):
    行 = []
    for x in 想起们 or []:
        if x.get("文"):
            行.append("「%s」" % str(x["文"])[:60])
    if not 行:
        return []
    return ["【你此刻想起】%s" % "；".join(行),
            "（这几件事自己冒出来的。可以带一句，但别把整句背出来，也别主动解释它。）"]


def 自检():
    好 = 总 = 0

    def 验(名, 条, 注=""):
        nonlocal 好, 总
        总 += 1
        好 += 1 if 条 else 0
        print("  %s %-42s %s" % ("✅" if 条 else "❌", 名, str(注)[:44]))

    验("标签：灾难", "灾难" in 标签("九八年发大水，屋子冲塌了"))
    验("标签：家人", "家人" in 标签("我儿子结婚那天"))
    验("效价：负", 效价("大水冲了屋子，死了人") < 0, 效价("大水冲了屋子，死了人"))
    验("效价：正", 效价("邻居救了我们，真是好人") > 0, 效价("邻居救了我们，真是好人"))
    验("效价：中性", 效价("今天天气还行") == 0)

    段 = 记段("九八年大水冲垮了屋子，一家人挤在堤上")
    验("一段历史有四件套", set(段) >= {"文", "标签", "效价", "威胁", "对抗"}, 段["标签"])
    验("威胁有值", 段["威胁"] > 0, 段["威胁"])

    场们 = 叠({"名": "收摊"}, "外面下暴雨了，你家没事吧")
    验("叠加出不止一场", len(场们) >= 2, [x["名"] for x in 场们])
    验("叠加里有时刻", any(x["来源"] == "此刻" for x in 场们))
    验("叠加里有刺激", any(x["来源"] == "对方这句" for x in 场们))

    档 = {"栏": {"历史": {"条目": [
        {"文": "九八年发大水，屋子冲塌了，一家人挤在堤上"},
        {"文": "我儿子一二年结婚，我背地里塞了两万块"},
        {"文": "去年我跟人吵了一架，被带去派出所"},
        {"文": "邻居划着盆把我们老小接出来"},
    ]}}}
    需求 = {"安全": 0.8, "生存": 0.7, "归属": 0.6, "尊重": 0.4, "掌控": 0.5}
    甲 = 抽(档, {"名": "收摊"}, "外面下暴雨了", 0.0,
            {"皮质醇": 0.4}, 需求, 种子=1)
    乙 = 抽(档, {"名": "收摊"}, "我儿子要结婚了，缺点钱", 0.0,
            {"皮质醇": 0.4}, 需求, 种子=1)
    验("问下雨 → 想起水灾那类", any("大水" in x["文"] for x in 甲["想起"]),
       [x["文"][:12] for x in 甲["想起"]])
    # ★ 概率性的东西不能拿单次抽样断言。跑 200 次看谁最常被想起。
    def 最常提到(对方话, 关键词, 次=200):
        中 = 0
        for 种 in range(次):
            r = 抽(档, {"名": "收摊"}, 对方话, 0.0, {"皮质醇": 0.4}, 需求, 种子=种)
            if any(关键词 in x["文"] for x in r["想起"]):
                中 += 1
        return 中 / float(次)

    比 = 最常提到("我儿子要结婚了，缺点钱", "儿子")
    比2 = 最常提到("我儿子要结婚了，缺点钱", "大水")
    验("问儿子结婚 → 「儿子那件事」比「大水」更常被想起", 比 > 比2, (round(比, 2), round(比2, 2)))
    验("而且占多数", 比 >= 0.5, 比)

    丙 = 抽(档, {"名": "收摊"}, "外面下暴雨了", 0.0,
            {"皮质醇": 0.95}, 需求, 种子=1)
    验("皮质醇高 → 想起的那段威胁更重",
       sum(x["威胁"] for x in 丙["想起"]) >= sum(x["威胁"] for x in 甲["想起"]),
       (sum(x["威胁"] for x in 丙["想起"]), sum(x["威胁"] for x in 甲["想起"])))

    同1 = 抽(档, {"名": "收摊"}, "外面下暴雨了", 0, {"皮质醇": 0.4}, 需求, 种子=9)
    同2 = 抽(档, {"名": "收摊"}, "外面下暴雨了", 0, {"皮质醇": 0.4}, 需求, 种子=9)
    验("同一个种子结果一样", [x["文"] for x in 同1["想起"]] == [x["文"] for x in 同2["想起"]])

    进 = 进提示词(甲["想起"])
    验("提示词里有想起", any("你此刻想起" in x for x in 进), 进[:1])
    验("空的不进提示词", 进提示词([]) == [])

    空档 = {"栏": {"历史": {"条目": []}}}
    验("没有历史也不报错", 抽(空档, {"名": "闲时"}, "在吗")["想起"] == [])

    print("\n  结果：%d 过 / %d 不过" % (好, 总 - 好))
    return 0 if 好 == 总 else 1


if __name__ == "__main__":
    sys.exit(自检())
