def 按钟点(时=None):
    import datetime
    时 = datetime.datetime.now().hour if 时 is None else 时
    if 6 <= 时 < 9:
        return "干活中"
    if 9 <= 时 < 11:
        return "干活中"
    if 11 <= 时 < 13:
        return "饭点"
    if 13 <= 时 < 18:
        return "干活中"
    if 18 <= 时 < 20:
        return "收摊"
    if 20 <= 时 < 23:
        return "闲时"
    return "夜里"


def 取(档, 时=None):
    r"""这个人此刻在哪一场。→ dict（总是有，最差是"闲时"）"""
    名 = ""
    try:
        条 = (((档 or {}).get("栏") or {}).get("当下状态") or {}).get("条目") or []
        文 = " ".join(str(x.get("文") or "") for x in 条)
        for 场名, 词们 in 词表:
            if any(w in 文 for w in 词们):
                名 = 场名
                break
    except Exception:
        名 = ""
    if not 名:
        名 = 按钟点(时)
    场 = dict(表.get(名) or 表["闲时"])
    场["名"] = 名 if 名 in 表 else "闲时"
    场.setdefault("名", "闲时")
    return 场


def 一句(场):
    r"""给界面用的一行：'他正在收摊'。"""
    return str((场 or {}).get("一句") or "他现在闲着，能聊")


def 进提示词(场):
    r"""喂给模型的三行。★ 这里才是"场景锚定情绪和需求"落地的地方。"""
    if not 场:
        return []
    长 = {"短": "句子很短，一句就完，别超过十五个字",
          "中": "句子不长，一两句说完",
          "长": "可以多说几句，但别写成小作文"}.get(场.get("句长"), "")
    行 = [
        "【眼下】%s（%s）" % (场.get("在干"), 场.get("时长")),
        "【这会儿的心情】%s；最想要的是：%s" % (场.get("情绪"), 场.get("需求")),
    ]
    if 场.get("怎么说"):
        行.append("【这会儿你怎么说话】%s" % 场["怎么说"])
    elif 长:
        行.append("【怎么开口】%s。" % 长)
    if 场.get("可断"):
        行.append("【可能断】你随时得去忙 —— 话可以短、可以只说一半，"
                  "但别编理由说自己忙（真忙就直接短）。")
    return 行


def 自检():
    好 = 总 = 0

    def 验(名, 条, 注=""):
        nonlocal 好, 总
        总 += 1
        好 += 1 if 条 else 0
        print("  %s %-40s %s" % ("✅" if 条 else "❌", 名, str(注)[:36]))

    验("表有七场戏", len(表) == 7, list(表))
    验("按钟点：早上是干活", 按钟点(8) == "干活中", 按钟点(8))
    验("按钟点：中午是饭点", 按钟点(12) == "饭点", 按钟点(12))
    验("按钟点：深夜是夜里", 按钟点(2) == "夜里", 按钟点(2))

    空档 = {"栏": {}}
    验("空档案也给得出一场", 取(空档, 15)["名"] in 表)
    收 = {"栏": {"当下状态": {"条目": [{"文": "正在收摊，天快黑了"}]}}}
    验("读得出「收摊」", 取(收)["名"] == "收摊", 取(收)["名"])
    干 = {"栏": {"当下状态": {"条目": [{"文": "手上正赶工，抽空看一眼"}]}}}
    验("读得出「干活中」", 取(干)["名"] == "干活中", 取(干)["名"])

    验("一句人话", "收摊" in 一句(表["收摊"]), 一句(表["收摊"]))
    进 = 进提示词(表["干活中"])
    验("提示词里有眼下", any("【眼下】" in x for x in 进), 进)
    验("提示词里有需求", any("最想要的是" in x for x in 进), 进)
    验("有「这会儿你怎么说话」", any("这会儿你怎么说话" in x for x in 进), 进)
    验("能断的场景会提醒", any("可能断" in x for x in 进))
    验("闲时不带可能断", not any("可能断" in x for x in 进提示词(表["闲时"])))

    print("\n  结果：%d 过 / %d 不过" % (好, 总 - 好))
    return 0 if 好 == 总 else 1


