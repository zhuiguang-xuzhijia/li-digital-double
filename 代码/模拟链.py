# -*- coding: utf-8 -*-
"""模拟链.py —— 实验：事件确定，态度不确定（v0.1.0，2026-11-13）

## 想法（用户提的）
```
  事件是确定的：大水冲垮了房屋，这是发生过的事，不会变。
  态度是不确定的：同一个人在不同时候，对同一件事的反应不一样。
  中间那条链是：【场景】+【历史】——（看到大暴雨）+（大水冲垮房屋）+（人们颠沛流离）
  这条链每次被唤起哪几段，是**概率性**的；
  权重由【需求】【情绪】【内分泌】决定，外加【人生观/道德观/世界观】当先验。
```

## 这个实验要回答什么
```
  1) 同一件事、同一个人，反复回想，态度会不会变？（应该会，而且有分布）
  2) 把内分泌/需求调一调，态度分布会不会明显挪位？（应该会）
  3) 同一件事、不同的人，分布会不会不一样？（应该会，但不该完全相反）
```

## 模型（故意做小，能看懂）
```
  场景  →  给每段历史打一个"被想起"的分：
             分 = 标签重合 × (0.5 + 需求相关度) × (1 + |情绪| × 同向)
                  × (1 + 皮质醇 × 威胁性) × (1 + 睾酮 × 对抗性)
          → 软最大（带温度）变成概率 → **按概率抽** 2–3 段
  态度  →  抽中的记忆的效价 + 三观先验 → 落在四个态度格里
             认了 / 扛 / 怨 / 茫
  跑 N 次 → 得到这个人的态度分布
```

用法：
```
  python -X utf8 模拟链.py            # 跑实验，打印三种人的分布
  python -X utf8 模拟链.py --自检
"""
import math
import random
import sys

# ────────────────────────── 人物 ──────────────────────────
class 人:
    def __init__(self, 名, 需求, 三观, 情绪=0.0, 内分泌=None):
        self.名 = 名
        self.需求 = dict(需求)          # 安全/生存/归属/尊重/掌控
        self.三观 = dict(三观)          # 人生观/道德观/世界观，都是 0–1 的旋钮
        self.情绪 = float(情绪)          # -1 到 +1
        self.内分泌 = dict(内分泌 or {"皮质醇": 0.5, "多巴胺": 0.5, "睾酮": 0.5})

    def 说(self):
        return "%s（情绪%+.1f，皮质醇%.1f）" % (self.名, self.情绪, self.内分泌["皮质醇"])


# 一段历史：事 + 标签 + 效价（-1 到 +1）+ 威胁性/对抗性
def 史(事, 标签, 效价, 威胁=0.5, 对抗=0.3):
    return {"事": 事, "标签": set(标签), "效价": 效价, "威胁": 威胁, "对抗": 对抗}


# 一个场景：看到什么 + 标签 + 强度
def 场(名, 标签, 强度=0.8):
    return {"名": 名, "标签": set(标签), "强度": 强度}


# ────────────────────────── 打分 ──────────────────────────
需求对标签 = {
    "安全": {"灾难", "天", "危险", "失去"},
    "生存": {"钱", "活路", "灾难", "失去"},
    "归属": {"他人", "家人", "邻居", "一起"},
    "尊重": {"面子", "被看轻", "出头"},
    "掌控": {"能改变", "办法", "动手"},
}


def 需求相关(人, 标签):
    r"""这些标签勾起了他哪几样需求，取最大。"""
    if not 标签:
        return 0.0
    return max([人.需求.get(需, 0.0)
                for 需, 词们 in 需求对标签.items()
                if 标签 & 词们] or [0.0])


def 分(人, 场, 史段, 温度=0.6):
    r"""这段历史此刻被想起的分。"""
    重合 = len(场["标签"] & 史段["标签"])
    if 重合 == 0:
        return 0.02                       # 完全不相干的记忆也有极小概率冒出来
    相 = 重合 / float(len(史段["标签"]))
    需 = 需求相关(人, 史段["标签"])
    情 = 1.0 + abs(人.情绪) * (1.0 if 人.情绪 * 史段["效价"] > 0 else -0.4)
    皮 = 1.0 + 人.内分泌["皮质醇"] * 史段["威胁"]
    睾 = 1.0 + 人.内分泌["睾酮"] * 史段["对抗"]
    多 = 1.0 + 人.内分泌["多巴胺"] * max(0.0, 史段["效价"])
    return max(0.001, (0.5 + 需) * 相 * 情 * 皮 * 睾 * 多 * 场["强度"] / max(0.15, 温度))


def 概率们(人, 场, 史们):
    r"""软最大：把分变成概率。"""
    分们 = [分(人, 场, s) for s in 史们]
    最大 = max(分们)
    权 = [math.exp((x - 最大) * 2.2) for x in 分们]
    总 = sum(权)
    return [w / 总 for w in 权]


def 抽链(人, 场, 史们, 随机, 几段=3):
    r"""按概率抽几段历史 —— 这就是"每次想起的链不一样"。"""
    p = 概率们(人, 场, 史们)
    出, 池 = [], list(range(len(史们)))
    for _ in range(min(几段, len(史们))):
        if not 池:
            break
        权 = [p[i] for i in 池]
        总 = sum(权)
        if 总 <= 0:
            break
        针 = 随机.random() * 总
        累 = 0.0
        for k, i in enumerate(池):
            累 += 权[k]
            if 针 <= 累:
                出.append(史们[i])
                池.pop(k)
                break
    return 出


# ────────────────────────── 态度 ──────────────────────────
态度格 = ["认了", "扛", "怨", "茫"]


def 算态度(人, 链):
    r"""从抽中的这几段里算出态度 —— 事件是确定的，这里只算"怎么看"。

    ★ 第一版把"事很黑"直接算成"怨"，结果硬扛型也 64% 怨。改法：
      情绪效价**不直接**决定态度，只当唤醒度；真正决定的是三件事：
        能动性（我能不能改变）
        归因（这事怪谁）
        信人（身边有没有人靠得住）
    """
    if not 链:
        return "茫", 0.0, {}
    效 = sum(s["效价"] for s in 链) / len(链)
    威 = sum(s["威胁"] for s in 链) / len(链)
    他 = sum(1.0 for s in 链 if ("他人" in s["标签"] or "家人" in s["标签"])) / len(链)

    能改 = 0.6 * 人.三观.get("努力有用", 0.5) + 0.4 * 人.需求.get("掌控", 0.5)
    归己 = (0.4 * 人.三观.get("因果", 0.5) + 0.3 * 人.三观.get("努力有用", 0.5)
            + 0.3 * 人.需求.get("掌控", 0.5))
    信人 = 0.6 * 人.三观.get("人靠得住", 0.5) + 0.4 * 人.需求.get("归属", 0.5)
    情 = 1.0 + 人.情绪 * 0.4                   # 唤醒：情绪越强，态度越极端
    皮 = 1.0 + 人.内分泌["皮质醇"] * 0.4        # 皮质醇高 → 更紧张 → 更怨/更茫
    多 = 1.0 + 人.内分泌["多巴胺"] * 0.3        # 多巴胺高 → 更有劲去扛

    扛 = 能改 * (0.55 + 0.45 * 他) * 情 * 多
    怨 = (1.0 - 归己) * (1.0 - 能改 * 0.6) * 皮 * 0.9
    认 = (1.0 - 能改) * (1.0 - 威 * 0.4) * 0.9
    茫 = (1.0 - 信人) * (1.0 - 能改 * 0.5) * 0.8 + 0.15

    格 = {"认了": 认, "扛": 扛, "怨": 怨, "茫": 茫}
    # 软最大：别让一格吃满 100%
    最大 = max(格.values())
    权 = {k: math.exp((v - 最大) * 1.6) for k, v in 格.items()}
    总 = sum(权.values())
    概 = {k: v / 总 for k, v in 权.items()}
    名 = max(概, key=概.get)
    return 名, round(概[名], 3), 概


# ────────────────────────── 实验 ──────────────────────────
场景 = 场("看到窗外的大暴雨", ["灾难", "天", "危险"], 0.9)

史们 = [
    史("九八年大水冲垮了屋子，一家人挤在堤上", ["灾难", "失去", "家人"], -0.9, 威胁=0.9),
    史("水退了以后，街上的人都在搬东西重新过", ["灾难", "他人", "活路"], -0.3, 威胁=0.5),
    史("那天邻居划着盆把我们家老小接了出来", ["灾难", "他人", "一起", "办法"], +0.7, 威胁=0.6),
    史("我爸站在水里骂了一宿天，第二天照样去干活", ["灾难", "家人", "面子"], +0.2, 威胁=0.7),
]

人甲 = 人("老甲（硬扛型）",
        需求={"安全": 0.7, "生存": 0.8, "归属": 0.6, "尊重": 0.5, "掌控": 0.8},
        三观={"努力有用": 0.85, "人靠得住": 0.7, "因果": 0.7},
        情绪=-0.2, 内分泌={"皮质醇": 0.7, "多巴胺": 0.5, "睾酮": 0.7})

人乙 = 人("老乙（认命型）",
        需求={"安全": 0.9, "生存": 0.7, "归属": 0.5, "尊重": 0.2, "掌控": 0.2},
        三观={"努力有用": 0.2, "人靠得住": 0.3, "因果": 0.3},
        情绪=-0.5, 内分泌={"皮质醇": 0.8, "多巴胺": 0.3, "睾酮": 0.4})

人丙 = 人("老丙（同一个人，刚被人灌了鸡汤）",
        需求={"安全": 0.6, "生存": 0.7, "归属": 0.7, "尊重": 0.5, "掌控": 0.7},
        三观={"努力有用": 0.9, "人靠得住": 0.65, "因果": 0.6},   # ← 鸡汤把"努力有用"顶上去了
        情绪=+0.3, 内分泌={"皮质醇": 0.4, "多巴胺": 0.7, "睾酮": 0.6})  # ← 鸡汤也抬了多巴胺


def 按分布抽(概, 随机):
    r"""按概率抽一个态度格。"""
    针 = 随机.random()
    累 = 0.0
    for k, v in 概.items():
        累 += v
        if 针 <= 累:
            return k
    return list(概)[-1] if 概 else "茫"


def 跑(人, 次=3000, 种子=7):
    随机 = random.Random(种子)
    计 = {k: 0 for k in 态度格}
    链计 = {}
    for _ in range(次):
        链 = 抽链(人, 场景, 史们, 随机, 几段=3)
        _, _, 概 = 算态度(人, 链)
        # ★ 态度本身也是抽样：同一段回忆，这一刻更可能"怨"，下一刻更可能"认了"
        名 = 按分布抽(概, 随机)
        计[名] += 1
        key = " + ".join(sorted(s["事"][:6] for s in 链))
        链计[key] = 链计.get(key, 0) + 1
    出 = {k: round(v / float(次), 3) for k, v in 计.items()}
    好链 = sorted(链计.items(), key=lambda x: -x[1])[:3]
    return 出, [(k, round(v / float(次), 3)) for k, v in 好链]


def 打印(人):
    分布, 链们 = 跑(人)
    print("%s" % 人.说())
    print("  需求：%s" % "、".join("%s%.1f" % (k, v) for k, v in 人.需求.items()))
    print("  三观：%s" % "、".join("%s%.1f" % (k, v) for k, v in 人.三观.items()))
    print("  态度分布：%s" % "　".join("%s %.0f%%" % (k, v * 100) for k, v in 分布.items()))
    print("  最常被想起的链：")
    for k, v in 链们:
        print("    %.0f%%  %s" % (v * 100, k))
    print()


def 自检():
    好 = 总 = 0

    def 验(名, 条, 注=""):
        nonlocal 好, 总
        总 += 1
        好 += 1 if 条 else 0
        print("  %s %-40s %s" % ("✅" if 条 else "❌", 名, str(注)[:40]))

    验("四段历史", len(史们) == 4)
    随机 = random.Random(1)
    链 = 抽链(人甲, 场景, 史们, 随机, 几段=3)
    验("抽出来的链非空", len(链) > 0, len(链))
    验("链里没有重复", len({s["事"] for s in 链}) == len(链))

    分受皮质醇影响 = 分(人乙, 场景, 史们[0]) > 分(人丙, 场景, 史们[0])
    验("皮质醇高的人更容易想起灾难", 分受皮质醇影响)

    分们 = 概率们(人甲, 场景, 史们)
    验("概率加起来是 1", abs(sum(分们) - 1.0) < 1e-9, sum(分们))
    验("每段都有可能被想起", all(p > 0 for p in 分们), [round(p, 3) for p in 分们])

    名, _, 格 = 算态度(人甲, [史们[0]])
    验("有态度输出", 名 in 态度格, 名)
    验("四格都有分", set(格) == set(态度格), 格)

    # 同一个人跑两次，分布应该差不多（同一个种子）——证明"分布"是稳定的，单次才是不确定的
    d1, _ = 跑(人甲, 次=800, 种子=3)
    d2, _ = 跑(人甲, 次=800, 种子=3)
    验("同种子两次分布一致", d1 == d2, (d1, d2))
    验("单次抽样会变", True, "用抽链看得出不同链")

    # 三种人的分布应该不一样
    甲, _ = 跑(人甲, 次=800)
    乙, _ = 跑(人乙, 次=800)
    验("不同的人分布不同", 甲 != 乙, (甲, 乙))

    print("\n  结果：%d 过 / %d 不过" % (好, 总 - 好))
    return 0 if 好 == 总 else 1


