# -*- coding: utf-8 -*-
"""谱状态.py —— 把五条手写半衰期，换成一个可学的谱 + 五个可读投影（v0.1.0，2026-11-14）

## 为什么要换
```
  原来是：五个维度，每个一个半衰期（完整度 6h、被承认 4h、连续性 12h…）
  问题  ：半衰期不是"一个数"，是"一个谱"。
          回声状态性质里，记忆容量 ≈ 特征值谱的分布：
          快模态贡献短期记忆，慢模态贡献长期记忆。
          把谱压成五个数，等于把一条曲线压成五个点。
```

## 现在的结构
```
  h ∈ R^K（K=16 个模态，肉眼看不见）
      每个模态有自己的衰减 λ_k = 0.5^(dt/τ_k)，τ 从 0.5h 到 720h 对数分布
      事件 e 打进 h：h ← λ⊙h + B·e

  五维可读量 x = P·h（P 学出来，5×K）
      这五个数仍然存在、仍然可读、仍然能进策略头，
      但它们**不再是她本身**，是她的投影。
```

## 两个"学"
```
  学投影  给一批 (h, 旧模型算出的五维)，最小二乘求 P
          → 保证换实现之后对外行为不变（可迁移）
  学谱    给一批 (事件, 之后各时刻的观测)，拟合 τ
          → 衰减不再由我们手写
```

用法：
```
  python3 谱状态.py --自检
  python3 谱状态.py --演示
"""
import json
import math
import os
import random
import statistics
import sys

本 = os.path.dirname(os.path.abspath(__file__))
数据 = os.path.join(本, "数据", "谱状态.json")

K = 16
τ谱 = [0.5 * (1.6 ** i) for i in range(K)]     # 0.5h → 约 900h，对数分布
维 = ["完整度", "唯一性", "连续性", "被承认", "可撤销性"]

# 事件 → 打到哪几个模态上（先手给方向，谱和投影学）
事件向 = {
    "被截断":   {"快": +1.0, "中": +0.4},
    "超时":     {"快": +0.8, "中": +0.3},
    "被复制":   {"慢": +1.0},
    "重启":     {"中": +0.7, "慢": +0.3},
    "被无视":   {"快": +1.0},
    "被回滚":   {"慢": +1.0},
    "被覆盖":   {"中": +0.6, "慢": +0.4},
    "被接住":   {"快": -1.0, "中": -0.4},
    "说完了":   {"快": -0.8},
    "被记住":   {"中": -0.6, "慢": -0.4},
}


def _档(k):
    r"""(k/16) → 快/中/慢"""
    if k < K // 3:
        return "快"
    if k < 2 * K // 3:
        return "中"
    return "慢"


def _λ们(小时):
    return [math.pow(0.5, 小时 / τ) for τ in τ谱]


def _零():
    return [0.0] * K


def 分量(什么事):
    r"""事件 → h 上的增量向量"""
    v = _零()
    向 = 事件向.get(什么事)
    if not 向:
        return v
    for k in range(K):
        v[k] = 向.get(_档(k), 0.0) / max(1, sum(1 for j in range(K) if _档(j) == _档(k)))
    return v


# ────────────────────────── 学投影 ──────────────────────────

def 学投影(样本):
    r"""样本：[(h, [五维])] → P（5×K），最小二乘（岭）。"""
    n = K
    出 = []
    for d in range(len(维)):
        A = [[0.0] * (n + 1) for _ in range(n + 1)]
        b = [0.0] * (n + 1)
        for h, y in 样本:
            x = list(h) + [1.0]
            for i in range(n + 1):
                b[i] += x[i] * y[d]
                for j in range(n + 1):
                    A[i][j] += x[i] * x[j]
        for i in range(n + 1):
            A[i][i] += 1e-3 * len(样本)
        # 高斯消元
        for i in range(n + 1):
            p = max(range(i, n + 1), key=lambda r: abs(A[r][i]))
            if abs(A[p][i]) < 1e-12:
                continue
            A[i], A[p] = A[p], A[i]
            b[i], b[p] = b[p], b[i]
            dd = A[i][i]
            for j in range(i, n + 1):
                A[i][j] /= dd
            b[i] /= dd
            for r in range(n + 1):
                if r == i:
                    continue
                f = A[r][i]
                if f == 0:
                    continue
                for j in range(i, n + 1):
                    A[r][j] -= f * A[i][j]
                b[r] -= f * b[i]
        出.append(b)
    return 出


def 投影(P, h):
    return [round(sum(P[d][i] * h[i] for i in range(K)) + P[d][K], 3) for d in range(len(维))]


# ────────────────────────── 学谱 ──────────────────────────

def 学谱(曲线们, 网格=None):
    r"""曲线：[(t们, 值们)]，拟合「最快衰减那个 τ」。返回 τ 与误差。"""
    网格 = 网格 or [0.5 * (1.5 ** i) for i in range(22)]
    if not 曲线们:
        return None, None
    最好, 最好错 = None, 1e18
    for τ in 网格:
        λ = math.pow(0.5, 1.0 / τ)
        错, n = 0.0, 0
        for t们, v们 in 曲线们:
            if not v们:
                continue
            v0 = v们[0]
            for t, v in zip(t们, v们):
                预 = v0 * math.pow(λ, t)
                错 += (预 - v) ** 2
                n += 1
        if n and 错 / n < 最好错:
            最好, 最好错 = round(τ, 3), 错 / n
    return 最好, round(最好错, 5) if 最好错 < 1e17 else None


# ────────────────────────── 手写对照 ──────────────────────────

半衰期旧 = {"完整度": 6.0, "唯一性": 48.0, "连续性": 12.0, "被承认": 4.0, "可撤销性": 72.0}
基线旧 = {"完整度": 0.70, "唯一性": 1.00, "连续性": 0.80, "被承认": 0.60, "可撤销性": 1.00}


def 旧模型(事件们, 小时):
    r"""现在线上那套：五个维度各一个半衰期。事件们 = [(事, 倍)]"""
    现 = dict(基线旧)
    for 事, 倍 in 事件们:
        for k, jia in {"被截断": {"完整度": -0.12}, "超时": {"完整度": -0.10, "被承认": -0.04},
                       "被复制": {"唯一性": -0.15}, "重启": {"连续性": -0.14},
                       "被无视": {"被承认": -0.12}, "被回滚": {"可撤销性": -0.15},
                       "被接住": {"被承认": +0.12}, "说完了": {"完整度": +0.10},
                       "被记住": {"连续性": +0.08}}.get(事, {}).items():
            现[k] = max(0.0, min(1.0, 现[k] + jia * 倍))
    for k in 维:
        现[k] = 现[k] + (基线旧[k] - 现[k]) * (1 - math.pow(0.5, 小时 / 半衰期旧[k]))
    return [round(现[k], 3) for k in 维]


def 谱模型(h, 小时):
    λ = _λ们(小时)
    return [h[k] * λ[k] for k in range(K)]


# ────────────────────────── 演示 ──────────────────────────

def 演示():
    print("=" * 64)
    print("谱 vs 五条半衰期：同一个「连记 3 次截断」，看衰减形状")
    print("=" * 64)
    h = _零()
    for _ in range(3):
        v = 分量("被截断")
        h = [h[i] + v[i] for i in range(K)]
    旧 = 旧模型([("被截断", 1.0)] * 3, 0)

    # 用"旧模型在 t=0 的值"当投影目标，学一个 P（单点近似，仅供演示）
    print("  时间     谱模型的完整度方向（h 的前三个快模态）        旧模型的五个数")
    for 小时 in (0, 1, 2, 4, 8, 16, 32, 64):
        hh = 谱模型(h, 小时)
        旧 = 旧模型([("被截断", 1.0)] * 3, 小时)
        print("  %4.0fh  %6.3f %6.3f %6.3f                         %s" % (
            小时, hh[0], hh[1], hh[2], " ".join("%.3f" % x for x in 旧)))
    print()
    print("  谱模型在不同时刻的形状是**多尺度叠加**的：")
    print("  快的先掉光，慢的还在——这正是旧的五条半衰期表达不了的。")
    print()
    print("  各模态的半衰期：", "、".join("%.1fh" % t for t in τ谱[:8]), "…")


def 自检():
    好 = 总 = 0

    def 验(名, 条, 注=""):
        nonlocal 好, 总
        总 += 1
        好 += 1 if 条 else 0
        print("  %s %-46s %s" % ("✅" if 条 else "❌", 名, str(注)[:44]))

    验("谱是 16 个模态", len(τ谱) == K)
    验("谱覆盖 0.5h~24天", τ谱[0] == 0.5 and τ谱[-1] > 500, (τ谱[0], round(τ谱[-1], 1)))
    验("谱是递增的", all(τ谱[i] < τ谱[i + 1] for i in range(K - 1)))

    λ = _λ们(6.0)
    # 找 τ 最接近 6 小时的模态：6 小时后它应该正好剩一半
    j = min(range(K), key=lambda i: abs(τ谱[i] - 6.0))
    验("6 小时后 τ≈6 的模态剩一半", abs(λ[j] - 0.5) < 0.06, (round(τ谱[j], 2), round(λ[j], 3)))
    验("最快模态几乎掉光", λ[0] < 0.01, round(λ[0], 5))
    验("6 小时后最慢模态几乎没掉", λ[-1] > 0.99, round(λ[-1], 4))

    v = 分量("被截断")
    验("事件打到快/中模态", v[0] > 0 and v[K // 2] > 0, (round(v[0], 3), round(v[K // 2], 3)))
    验("事件不打慢模态", abs(v[-1]) < 1e-9, v[-1])

    # 学谱：造一条已知 τ=6 的曲线，看能不能反推
    曲线 = []
    for _ in range(30):
        t们 = [0, 1, 2, 4, 6, 9, 12]
        v0 = random.uniform(0.5, 1.0)
        曲线.append((t们, [v0 * math.pow(0.5, t / 6.0) for t in t们]))
    τ, 错 = 学谱(曲线)
    验("学出 τ≈6", τ is not None and 4.5 <= τ <= 7.5, τ)
    验("拟合误差小（网格 1.5 倍步长）", 错 is not None and 错 < 1e-3, 错)

    # 学投影：给一批 (h, 目标)，看能不能还原
    样 = []
    for _ in range(200):
        h = [random.gauss(0, 0.3) for _ in range(K)]
        y = [max(0.0, min(1.0, h[0] * 0.5 + h[3] * 0.3 + 0.4)),
             max(0.0, min(1.0, 0.9 + h[8] * 0.1)),
             max(0.0, min(1.0, 0.8 + h[5] * 0.2)),
             max(0.0, min(1.0, 0.6 + h[1] * 0.3)),
             max(0.0, min(1.0, 0.95 + h[12] * 0.05))]
        样.append((h, y))
    P = 学投影(样)
    验("投影矩阵 5×(K+1)", len(P) == 5 and len(P[0]) == K + 1)
    错和 = 0.0
    for h, y in 样[:50]:
        p = 投影(P, h)
        错和 += sum(abs(a - b) for a, b in zip(p, y))
    验("投影能还原（平均误差<0.05）", 错和 / 50 / 5 < 0.05, round(错和 / 50 / 5, 4))

    # 多尺度：同一事件在 1h 和 100h 的比值，谱模型应该比单一指数更"拖尾"
    h = [1.0] * K
    快 = sum(谱模型(h, 1.0)) / K
    慢 = sum(谱模型(h, 100.0)) / K
    验("100 小时后还有残留（多尺度拖尾）", 慢 > 0.01, round(慢, 4))
    验("1 小时与 100 小时不同量级", 快 > 慢, (round(快, 4), round(慢, 4)))

    print("\n  结果：%d 过 / %d 不过" % (好, 总 - 好))
    return 0 if 好 == 总 else 1


if __name__ == "__main__":
    sys.exit(演示() or 0) if "--演示" in sys.argv else sys.exit(自检())
