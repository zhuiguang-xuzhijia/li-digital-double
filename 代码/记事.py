# -*- coding: utf-8 -*-
"""记事.py —— 把人在聊天里说出的「重要事件」，录进他自己的档案（v0.1.0，2026-11-13）

## 为什么要有这个
```
  检查发现：一个人聊天时说的"九八年发大水，我家摊子冲了"——这些话
  **一条都不会进档案**。只在关系卡里留 30 个字的"事件"，还是给情绪算分用的，200 条一滚就没了。
  档案的「历史」栏只有两个来源：造人时模型编的、每日两问答题时写的。
  聊天里说的真事，全丢了。
```

## 什么能称为「重要事件」（判据，能数出来，不靠感觉）
```
  ① 有时间锚：1998 / 九八年 / 去年 / 那年 / 小时候 / 上个月 / 结婚那年
  ② 或有人物锚 + 动作：我爸住院 / 我儿子结婚 / 我妈走了 / 我师父教我 / 我老婆跑了
  ③ 或有转折词：死 走 病 住院 离婚 结婚 搬 丢 欠 赔 进 出 抓 关 借钱 还钱 打架
  ④ 长度 ≥ 8 字（"嗯""好的"这种不算事）
  ⑤ 不是问句（问"你那年咋了"是打听，不是自己的事）
  ⑥ 同一件事不重复记（跟已有的历史条目相似就跳过）
```

## 记到哪
```
  档案「历史」栏，来源=观察，问=聊天
  → 他的分身以后说"我"的时候，能拿这件事当真事用
```

用法：
```
  python -X utf8 记事.py --自检
  python -X utf8 记事.py --回填     # 把历史会话里的重要事件捞一遍
"""
import json
import os
import re
import sys
import time

本 = os.path.dirname(os.path.abspath(__file__))
if 本 not in sys.path:
    sys.path.insert(0, 本)

# 时间锚
时锚 = re.compile(
    r"(19|20)\d{2}|[零一二三四五六七八九]{2}年|[零一二三四五六七八九]年"
    r"|去年|前年|那年|那年头|小时候|年轻时候|前些年|上个月|今年|去年冬天|"
    r"结婚那年|刚来|刚上班|刚结婚")

# 人物锚
人锚 = re.compile(
    r"我(爸|妈|爹|娘|哥|姐|弟|妹|儿子|闺女|女儿|媳妇|老婆|老公|爱人|老伴|师父|师傅|"
    r"姐们|兄弟|邻居|发小|老板|徒弟)")

# 转折词（真出事的那种）
转折 = re.compile(
    r"死|走了|没了|病|住院|手术|癌|离婚|结婚|生孩子|出生|搬|丢了|欠|赔|"
    r"抓|关进去|判|蹲|进厂|下岗|失业|倒闭|拆迁|打官司|出车祸|借钱|还钱|"
    r"吵翻|闹翻|跑了|退了|考上|没考上|入伍|退伍")

疑问 = re.compile(r"[?？]|吗|呢|是不是|有没有|咋样|怎么样")

停用 = ("好的", "嗯", "行", "哈哈", "在吗", "收到", "知道了")


def 是不是事(话):
    r"""→ (是?, 命中了什么)。判据全写在 docstring 里。"""
    话 = str(话 or "").strip()
    if len(话) < 8:
        return False, "太短"
    if 话 in 停用:
        return False, "口头语"
    if 疑问.search(话):
        return False, "是问句（打听别人，不是自己的事）"
    中 = []
    if 时锚.search(话):
        中.append("时间锚")
    if 人锚.search(话):
        中.append("人物锚")
    if 转折.search(话):
        中.append("转折")
    if len(中) >= 2:
        return True, "、".join(中)
    if "时间锚" in 中 and len(话) >= 14:
        return True, "时间锚+说清了"
    if "转折" in 中 and 人锚.search(话):
        return True, "人物+转折"
    return False, "不像事" + ("（只命中%s）" % "、".join(中) if 中 else "")


def _像(甲, 乙):
    r"""粗相似：共同的两字片段占比。用来去重。"""
    def 片(s):
        s = re.sub(r"[^\u4e00-\u9fa5]", "", str(s))
        return {s[i:i + 2] for i in range(max(0, len(s) - 1))}
    a, b = 片(甲), 片(乙)
    if not a or not b:
        return 0.0
    return len(a & b) / float(min(len(a), len(b)))


def 记(账号, 话, 档=None):
    r"""这句话里的事，记进这个人的「历史」。→ (记了?, 说)"""
    import 档案 as D
    好, 因 = 是不是事(话)
    if not 好:
        return False, 因
    文 = str(话).strip()[:100]
    try:
        档 = 档 or D.读(账号)
    except Exception:
        return False, "读不到档案"
    旧 = [str(x.get("文") or "") for x in
          ((档.get("栏") or {}).get("历史") or {}).get("条目") or []]
    for x in 旧:
        if _像(x, 文) >= 0.55:
            return False, "已经记过了"
    成, _ = D.加(档, "历史", 文, 来源="观察", 问="聊天")
    if 成:
        D.写(档)
        return True, "记下了（%s）" % 因
    return False, "没收进去"


def 回填():
    r"""把历史会话里"人自己说过的重要事件"捞一遍。→ (记了, 几个人)"""
    会路 = os.path.join(本, "数据", "真人", "会话.json")
    if not os.path.isfile(会路):
        return 0, 0
    会们 = json.load(open(会路, encoding="utf-8"))
    人 = {}
    for 会 in 会们.values():
        甲, 乙 = str(会.get("甲") or ""), str(会.get("乙") or "")
        for m in (会.get("消息") or []):
            谁 = str(m.get("谁") or "")
            if 谁 in (甲, 乙) and str(m.get("话") or "").strip():
                人.setdefault(谁, []).append(str(m.get("话")))
    共 = 0
    谁们 = set()
    for 号, 话们 in 人.items():
        for 话 in 话们:
            if 记(号, 话)[0]:
                共 += 1
                谁们.add(号)
    return 共, len(谁们)


def 自检():
    好 = 总 = 0

    def 验(名, 条, 注=""):
        nonlocal 好, 总
        总 += 1
        好 += 1 if 条 else 0
        print("  %s %-42s %s" % ("✅" if 条 else "❌", 名, str(注)[:40]))

    真事 = [
        "九八年发大水，我家摊子冲了，我守了三天",
        "我爸去年走了，走之前一直念叨我",
        "一二年我儿子结婚，我背地里塞了两万",
        "去年冬天我住院，没人来看我",
        "我老婆那会儿跟我闹离婚，闹了半年",
    ]
    for x in 真事:
        验("认得出：" + x[:12], 是不是事(x)[0], 是不是事(x)[1])

    假事 = [
        "嗯",
        "好的我知道了谢谢你啊",
        "你那年咋了啊？",
        "今天天气不错啊哈哈",
        "在吗在吗在吗",
    ]
    for x in 假事:
        验("不算事：" + x[:12], not 是不是事(x)[0], 是不是事(x)[1])

    验("相似句能去重", _像("九八年发大水摊子冲了", "九八年发大水，我家摊子冲了") >= 0.55,
       _像("九八年发大水摊子冲了", "九八年发大水，我家摊子冲了"))
    验("不同的事不比", _像("我爸去年走了", "我儿子结婚") < 0.4,
       _像("我爸去年走了", "我儿子结婚"))

    print("\n  结果：%d 过 / %d 不过" % (好, 总 - 好))
    return 0 if 好 == 总 else 1


if __name__ == "__main__":
    if "--回填" in sys.argv:
        记了, 几 = 回填()
        print("回填：记了 %d 件事，涉及 %d 个人" % (记了, 几))
    else:
        sys.exit(自检())
